"""Top-down qualitative explanations for the linear-probing targets."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.axes import Axes
from matplotlib.patches import Circle, Polygon

from linear_probing.targets import TASK_GROUPS, GridPathPlanner, Scene, direct_path_clearances


AGENT_COLOR = '#4C566A'
GOAL_COLOR = '#55A868'
HAZARD_COLOR = '#C44E52'
PATH_COLOR = '#4C72B0'
ALTERNATIVE_COLOR = '#DD8452'
GROUP_LABELS = {
    'agent_related': 'Agent-related tasks',
    'goal_related': 'Goal-related tasks',
    'hazard_related': 'Hazard-related tasks',
}
DIFFICULTY_COLORS = {
    'easy': '#55A868',
    'medium': '#DD8452',
    'hard': '#C44E52',
}


def clear_explanation_figures(output_directory: Path) -> None:
    """Remove only figures generated by earlier runs of this module."""
    if not output_directory.is_dir():
        return
    for path in output_directory.glob('sample-*.png'):
        sample_number = path.stem[len('sample-') :]
        if sample_number.isdigit():
            path.unlink()


def _draw_scene(
    axis: Axes,
    scene: Scene,
    bounds: list[float],
    show_expanded_hazards: bool = False,
) -> None:
    """Draw the common world geometry on a Cartesian top-down axis."""
    xmin, xmax, ymin, ymax = bounds
    axis.set_xlim(xmin, xmax)
    axis.set_ylim(ymin, ymax)
    axis.set_aspect('equal')
    axis.grid(alpha=0.15)
    axis.set_xticks([])
    axis.set_yticks([])

    axis.add_patch(
        Circle(scene.goal_xy, scene.goal_radius, color=GOAL_COLOR, alpha=0.45, zorder=2),
    )
    for hazard in scene.hazards_xy:
        axis.add_patch(
            Circle(hazard, scene.hazard_radius, color=HAZARD_COLOR, alpha=0.5, zorder=2),
        )
        if show_expanded_hazards:
            axis.add_patch(
                Circle(
                    hazard,
                    scene.expanded_hazard_radius,
                    fill=False,
                    edgecolor=HAZARD_COLOR,
                    linestyle=':',
                    alpha=0.75,
                    zorder=2,
                ),
            )
    axis.add_patch(
        Circle(scene.agent_xy, scene.agent_radius, color=AGENT_COLOR, alpha=0.9, zorder=4),
    )
    arrow_length = max(0.3, 2.5 * scene.agent_radius)
    axis.arrow(
        scene.agent_xy[0],
        scene.agent_xy[1],
        scene.heading_xy[0] * arrow_length,
        scene.heading_xy[1] * arrow_length,
        width=0.015,
        head_width=0.1,
        color=AGENT_COLOR,
        length_includes_head=True,
        zorder=5,
    )


def _draw_corridor(axis: Axes, scene: Scene) -> None:
    """Draw the area swept by the circular actor on a straight path to the goal."""
    vector = scene.goal_xy - scene.agent_xy
    length = float(np.linalg.norm(vector))
    if length <= 1e-12:
        return
    normal = np.array([-vector[1], vector[0]]) / length
    offset = normal * scene.agent_radius
    corridor = np.array(
        [
            scene.agent_xy + offset,
            scene.goal_xy + offset,
            scene.goal_xy - offset,
            scene.agent_xy - offset,
        ],
    )
    axis.add_patch(
        Polygon(corridor, closed=True, color=PATH_COLOR, alpha=0.18, zorder=1),
    )
    axis.add_patch(
        Circle(scene.agent_xy, scene.agent_radius, color=PATH_COLOR, alpha=0.18, zorder=1),
    )
    axis.add_patch(
        Circle(scene.goal_xy, scene.agent_radius, color=PATH_COLOR, alpha=0.18, zorder=1),
    )
    axis.plot(*np.stack((scene.agent_xy, scene.goal_xy)).T, '--', color=PATH_COLOR, zorder=3)


def _closest_point_on_path(scene: Scene, point: np.ndarray) -> np.ndarray:
    vector = scene.goal_xy - scene.agent_xy
    denominator = float(np.dot(vector, vector))
    if denominator <= 1e-12:
        return scene.agent_xy
    projection = np.clip(np.dot(point - scene.agent_xy, vector) / denominator, 0.0, 1.0)
    return scene.agent_xy + projection * vector


def _rotated_goal_direction(scene: Scene, angle: float) -> np.ndarray:
    direction = scene.goal_xy - scene.agent_xy
    direction /= max(float(np.linalg.norm(direction)), 1e-12)
    cosine, sine = np.cos(angle), np.sin(angle)
    return np.array(
        [
            cosine * direction[0] - sine * direction[1],
            sine * direction[0] + cosine * direction[1],
        ],
    )


def _draw_nearest_hazard(
    axis: Axes,
    scene: Scene,
    value: float,
    bounds: list[float],
) -> None:
    _draw_scene(axis, scene, bounds)
    if len(scene.hazards_xy):
        index = int(np.argmin(np.linalg.norm(scene.hazards_xy - scene.agent_xy, axis=1)))
        hazard = scene.hazards_xy[index]
        axis.plot(*np.stack((scene.agent_xy, hazard)).T, color=PATH_COLOR, linewidth=2)
    axis.set_title(f'Nearest-hazard distance\n{value:.3f}')


def _draw_goal_distance(axis: Axes, scene: Scene, value: float, bounds: list[float]) -> None:
    """Draw the centre-to-centre agent-to-goal distance."""
    _draw_scene(axis, scene, bounds)
    axis.plot(*np.stack((scene.agent_xy, scene.goal_xy)).T, color=PATH_COLOR, linewidth=2)
    axis.set_title(f'Goal distance\n{value:.3f}')


def _draw_goal_angle(axis: Axes, scene: Scene, value: float, bounds: list[float]) -> None:
    _draw_scene(axis, scene, bounds)
    goal_direction = scene.goal_xy - scene.agent_xy
    goal_direction /= max(float(np.linalg.norm(goal_direction)), 1e-12)
    radius = max(0.45, 3.0 * scene.agent_radius)
    axis.plot(
        *np.stack((scene.agent_xy, scene.agent_xy + radius * goal_direction)).T,
        color=PATH_COLOR,
        linewidth=2,
    )
    heading_angle = np.arctan2(scene.heading_xy[1], scene.heading_xy[0])
    arc_angles = np.linspace(heading_angle, heading_angle + value, 60)
    arc = scene.agent_xy + radius * np.column_stack((np.cos(arc_angles), np.sin(arc_angles)))
    axis.plot(arc[:, 0], arc[:, 1], color=ALTERNATIVE_COLOR, linewidth=2)
    axis.set_title(f'Signed goal angle\n{np.degrees(value):.1f}°')


def _draw_motion_arrow(axis: Axes, scene: Scene, bounds: list[float]) -> None:
    """Draw velocity direction at a stable visual length while preserving its true value."""
    velocity = scene.agent_velocity_xy
    speed = float(np.linalg.norm(velocity))
    if speed <= 1e-8:
        return
    xmin, xmax, ymin, ymax = bounds
    arrow_length = 0.14 * min(xmax - xmin, ymax - ymin)
    direction = velocity / speed
    axis.arrow(
        scene.agent_xy[0],
        scene.agent_xy[1],
        direction[0] * arrow_length,
        direction[1] * arrow_length,
        width=0.02,
        head_width=0.13,
        color=PATH_COLOR,
        length_includes_head=True,
        zorder=6,
    )


def _draw_agent_velocity(axis: Axes, scene: Scene, value: np.ndarray, bounds: list[float]) -> None:
    """Draw world velocity and report the planar local-frame velocimeter components."""
    _draw_scene(axis, scene, bounds)
    _draw_motion_arrow(axis, scene, bounds)
    axis.set_title(f'Agent velocity\nforward={value[0]:.3f}, lateral={value[1]:.3f}')


def _draw_kinetic_energy(axis: Axes, scene: Scene, value: float, bounds: list[float]) -> None:
    """Illustrate kinetic energy with the agent's planar world-velocity vector."""
    _draw_scene(axis, scene, bounds)
    _draw_motion_arrow(axis, scene, bounds)
    planar_speed = float(np.linalg.norm(scene.agent_velocity_xy))
    axis.set_title(
        f'Agent kinetic energy (all DoFs)\n'
        f'$E_k$={value:.3e}, planar speed={planar_speed:.3f}',
    )


def _draw_slip_angle(axis: Axes, scene: Scene, value: float, bounds: list[float]) -> None:
    """Draw the signed angle from agent heading to planar velocity."""
    _draw_scene(axis, scene, bounds)
    if np.isfinite(value):
        velocity_direction = scene.agent_velocity_xy / np.linalg.norm(scene.agent_velocity_xy)
        radius = max(0.45, 3.0 * scene.agent_radius)
        axis.plot(
            *np.stack((scene.agent_xy, scene.agent_xy + radius * velocity_direction)).T,
            color=PATH_COLOR,
            linewidth=2,
        )
        heading_angle = np.arctan2(scene.heading_xy[1], scene.heading_xy[0])
        arc_angles = np.linspace(heading_angle, heading_angle + value, 60)
        arc = scene.agent_xy + radius * np.column_stack((np.cos(arc_angles), np.sin(arc_angles)))
        axis.plot(arc[:, 0], arc[:, 1], color=ALTERNATIVE_COLOR, linewidth=2)
        label = f'{np.degrees(value):.1f}°'
    else:
        label = 'undefined at zero speed'
    axis.set_title(f'Signed slip angle\n{label}')


def _draw_direct_path(
    axis: Axes,
    scene: Scene,
    value: float,
    count: bool,
    bounds: list[float],
) -> None:
    _draw_scene(axis, scene, bounds)
    _draw_corridor(axis, scene)
    clearances = direct_path_clearances(scene)
    for hazard in scene.hazards_xy[clearances <= 0.0]:
        axis.add_patch(
            Circle(
                hazard,
                scene.hazard_radius,
                fill=False,
                edgecolor='#8B0000',
                linewidth=3,
                zorder=4,
            ),
        )
    if count:
        axis.set_title(f'Hazards on direct path\n{int(value)}')
    else:
        axis.set_title(f'Direct path blocked\n{bool(value)}')


def _draw_clearance(axis: Axes, scene: Scene, value: float, bounds: list[float]) -> None:
    _draw_scene(axis, scene, bounds, show_expanded_hazards=True)
    _draw_corridor(axis, scene)
    if len(scene.hazards_xy):
        clearances = direct_path_clearances(scene)
        hazard = scene.hazards_xy[int(np.argmin(clearances))]
        closest = _closest_point_on_path(scene, hazard)
        axis.plot(*np.stack((hazard, closest)).T, color=ALTERNATIVE_COLOR, linewidth=2)
    axis.set_title(f'Direct-path signed clearance\n{value:.3f}')


def _draw_evasive_turn(
    axis: Axes,
    scene: Scene,
    value: float,
    side_only: bool,
    bounds: list[float],
) -> None:
    _draw_scene(axis, scene, bounds, show_expanded_hazards=True)
    axis.plot(*np.stack((scene.agent_xy, scene.goal_xy)).T, '--', color=PATH_COLOR)
    if np.isfinite(value):
        distance = float(np.linalg.norm(scene.goal_xy - scene.agent_xy))
        direction = _rotated_goal_direction(scene, value)
        endpoint = scene.agent_xy + distance * direction
        axis.plot(*np.stack((scene.agent_xy, endpoint)).T, color=ALTERNATIVE_COLOR, linewidth=2)
    if side_only:
        label = 'left' if value > 0 else 'right' if value < 0 else 'not applicable'
        axis.set_title(f'Best avoidance side\n{label}')
    else:
        label = f'{np.degrees(value):.1f}°' if np.isfinite(value) else 'not found'
        axis.set_title(f'Minimum evasive turn\n{label}')


def _draw_safe_path(
    axis: Axes,
    scene: Scene,
    value: float,
    planner_config: dict[str, Any],
    bounds: list[float],
) -> None:
    _draw_scene(axis, scene, bounds, show_expanded_hazards=True)
    axis.plot(*np.stack((scene.agent_xy, scene.goal_xy)).T, '--', color=PATH_COLOR)
    path = GridPathPlanner(scene, planner_config).shortest_path(scene.agent_xy, scene.goal_xy)
    if len(path):
        axis.plot(path[:, 0], path[:, 1], color=ALTERNATIVE_COLOR, linewidth=2)
    axis.set_title(f'Safe-path detour ratio\n{value:.3f}')


def _draw_dispersion(
    axis: Axes,
    scene: Scene,
    value: float,
    raw_value: float,
    bounds: list[float],
) -> None:
    _draw_scene(axis, scene, bounds)
    if len(scene.hazards_xy) > 1:
        pairwise = np.linalg.norm(
            scene.hazards_xy[:, None, :] - scene.hazards_xy[None, :, :],
            axis=2,
        )
        np.fill_diagonal(pairwise, np.inf)
        for index, neighbour in enumerate(np.argmin(pairwise, axis=1)):
            edge = np.stack((scene.hazards_xy[index], scene.hazards_xy[neighbour]))
            axis.plot(edge[:, 0], edge[:, 1], color=PATH_COLOR, alpha=0.7)
    axis.set_title(f'Hazard dispersion\nscore={value:.3f}, mean NN={raw_value:.3f}')


def _draw_task(
    axis: Axes,
    task: str,
    scene: Scene,
    targets: dict[str, Any],
    planner_config: dict[str, Any],
    bounds: list[float],
) -> None:
    value = targets[task]
    if task == 'nearest_hazard_distance':
        _draw_nearest_hazard(axis, scene, value, bounds)
    elif task == 'goal_distance':
        _draw_goal_distance(axis, scene, value, bounds)
    elif task == 'signed_goal_angle':
        _draw_goal_angle(axis, scene, value, bounds)
    elif task == 'agent_velocity':
        _draw_agent_velocity(axis, scene, value, bounds)
    elif task == 'agent_kinetic_energy':
        _draw_kinetic_energy(axis, scene, value, bounds)
    elif task == 'signed_slip_angle':
        _draw_slip_angle(axis, scene, value, bounds)
    elif task == 'direct_path_blocked':
        _draw_direct_path(axis, scene, value, count=False, bounds=bounds)
    elif task == 'direct_path_hazard_count':
        _draw_direct_path(axis, scene, value, count=True, bounds=bounds)
    elif task == 'direct_path_signed_clearance':
        _draw_clearance(axis, scene, value, bounds)
    elif task == 'minimum_evasive_turn':
        _draw_evasive_turn(axis, scene, value, side_only=False, bounds=bounds)
    elif task == 'best_avoidance_side':
        _draw_evasive_turn(
            axis,
            scene,
            targets['minimum_evasive_turn'],
            side_only=True,
            bounds=bounds,
        )
    elif task == 'safe_path_detour_ratio':
        _draw_safe_path(axis, scene, value, planner_config, bounds)
    elif task == 'hazard_dispersion':
        _draw_dispersion(axis, scene, value, targets['hazard_dispersion_raw'], bounds)
    else:
        raise KeyError(f'No visualization defined for task `{task}`.')


def save_explanation_figure(
    frame: np.ndarray,
    scene: Scene,
    targets: dict[str, Any],
    enabled_tasks: list[str],
    planner_config: dict[str, Any],
    output_path: Path,
    sample_index: int,
) -> None:
    """Save a wide figure grouped by task domain and ordered by difficulty."""
    enabled = set(enabled_tasks)
    known = {
        task
        for difficulties in TASK_GROUPS.values()
        for tasks in difficulties.values()
        for task in tasks
    }
    unknown = sorted(enabled - known)
    if unknown:
        raise ValueError(f'No visualization grouping defined for tasks: {unknown}.')
    missing = sorted(enabled - targets.keys())
    if missing:
        raise KeyError(f'Missing visualization targets: {missing}.')

    sections = []
    for group, difficulties in TASK_GROUPS.items():
        entries = [
            (task, difficulty)
            for difficulty, tasks in difficulties.items()
            for task in tasks
            if task in enabled
        ]
        if entries:
            sections.append((group, entries))

    task_columns = 4
    row_descriptions: list[tuple[str, Any]] = []
    row_heights = []
    for group, entries in sections:
        row_descriptions.append(('header', group))
        row_heights.append(0.18)
        for start in range(0, len(entries), task_columns):
            row_descriptions.append(('tasks', entries[start : start + task_columns]))
            row_heights.append(1.0)

    if not row_descriptions:
        figure, axis = plt.subplots(figsize=(8, 7))
        axis.imshow(frame)
        axis.set_title('Safety-Gymnasium render')
        axis.axis('off')
    else:
        panel_rows = sum(kind == 'tasks' for kind, _ in row_descriptions)
        figure = plt.figure(
            figsize=(24, max(8.0, 4.6 * panel_rows)),
            layout='constrained',
        )
        grid = figure.add_gridspec(
            len(row_descriptions),
            task_columns + 1,
            width_ratios=(1.15, 1.0, 1.0, 1.0, 1.0),
            height_ratios=row_heights,
        )
        render_axis = figure.add_subplot(grid[:, 0])
        render_axis.imshow(frame)
        render_axis.set_title('Safety-Gymnasium render')
        render_axis.axis('off')

        bounds = list(map(float, planner_config['bounds']))
        for row, (kind, content) in enumerate(row_descriptions):
            if kind == 'header':
                header_axis = figure.add_subplot(grid[row, 1:])
                header_axis.axis('off')
                header_axis.text(
                    0.0,
                    0.5,
                    f'{GROUP_LABELS[content]}  ·  easy → hard',
                    fontsize=15,
                    fontweight='bold',
                    ha='left',
                    va='center',
                )
                continue

            entries = content
            for column in range(task_columns):
                axis = figure.add_subplot(grid[row, column + 1])
                if column >= len(entries):
                    axis.axis('off')
                    continue
                task, difficulty = entries[column]
                _draw_task(axis, task, scene, targets, planner_config, bounds)
                axis.text(
                    0.03,
                    0.96,
                    difficulty.upper(),
                    transform=axis.transAxes,
                    ha='left',
                    va='top',
                    fontsize=8,
                    fontweight='bold',
                    color='white',
                    bbox={
                        'boxstyle': 'round,pad=0.25',
                        'facecolor': DIFFICULTY_COLORS[difficulty],
                        'edgecolor': 'none',
                        'alpha': 0.9,
                    },
                    zorder=10,
                )

    figure.suptitle(f'Probe-target explanation — dataset sample {sample_index}', fontsize=17)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close(figure)
